export function groupIcon(groupId: string): LucideIcon {
  return groupIcons[groupId] ?? MapPin
}

/** Categories without their own icon (the card sets) use their group's icon. */
export function categoryIcon(category: { id: string; group: string }): LucideIcon {
  return categoryIcons[category.id] ?? groupIcon(category.group)
}
